/// Generates `lib/src/generated/assets.g.dart` from a directory of built web
/// files so the agent binary can serve the client without touching disk.
///
/// Usage: `dart run tool/embed_assets.dart <input-dir> <output-file>`
///
/// When `<input-dir>` does not exist an empty bundle is written, so analysis
/// and tests work before the web client has been built (`make web`).
library;

import 'dart:convert';
import 'dart:io';

import 'package:crypto/crypto.dart';
import 'package:path/path.dart' as p;
import 'package:tp_agent/src/assets/content_types.dart';

/// Base64 characters per generated source line.
const int _lineWidth = 76;

Future<void> main(List<String> args) async {
  if (args.length != 2) {
    stderr.writeln(
      'usage: dart run tool/embed_assets.dart <input-dir> <output-file>',
    );
    exitCode = 64;
    return;
  }
  final inputDir = Directory(args[0]);
  final outputFile = File(args[1]);

  final files = <String, List<int>>{};
  if (inputDir.existsSync()) {
    await for (final entity in inputDir.list(
      recursive: true,
      followLinks: false,
    )) {
      if (entity is! File) continue;
      final relative = p.relative(entity.path, from: inputDir.path);
      files[p.posix.joinAll(p.split(relative))] = await entity.readAsBytes();
    }
  } else {
    stderr.writeln(
      'embed_assets: ${inputDir.path} not found; writing an empty bundle',
    );
  }

  final source = generateAssetSource(files);
  if (outputFile.existsSync() && outputFile.readAsStringSync() == source) {
    return; // Unchanged: keep the mtime so incremental builds stay quiet.
  }
  outputFile.parent.createSync(recursive: true);
  outputFile.writeAsStringSync(source);
  stdout.writeln(
    'embed_assets: wrote ${files.length} asset(s) to ${outputFile.path}',
  );
}

/// Returns the `Content-Type` for [path] based on its extension.
String contentTypeFor(String path) => contentTypeForPath(path);

/// Produces the Dart source of the asset bundle for [files] (path to raw
/// bytes). Output is deterministic: assets are sorted by path.
String generateAssetSource(Map<String, List<int>> files) {
  final gzip = GZipCodec(level: 9);
  final buf = StringBuffer()
    ..writeln('// GENERATED CODE - DO NOT MODIFY BY HAND')
    ..writeln('// Generated by tool/embed_assets.dart (`make embed`).')
    ..writeln('// dart format off')
    ..writeln()
    ..writeln("import '../assets/embedded_asset.dart';")
    ..writeln()
    ..writeln(
      '/// Web client files served by the agent, keyed by URL path '
      '(no leading slash).',
    )
    ..writeln(
      'const Map<String, EmbeddedAsset> embeddedAssets = '
      '<String, EmbeddedAsset>{',
    );

  for (final path in files.keys.toList()..sort()) {
    final raw = files[path]!;
    final etag = sha256.convert(raw).toString().substring(0, 16);
    final b64 = base64Encode(gzip.encode(raw));
    final chunks = <String>[];
    for (var i = 0; i < b64.length; i += _lineWidth) {
      final end = i + _lineWidth < b64.length ? i + _lineWidth : b64.length;
      chunks.add("        '${b64.substring(i, end)}'");
    }
    if (chunks.isEmpty) chunks.add("        ''");

    buf
      ..writeln("  '${_escape(path)}': EmbeddedAsset(")
      ..writeln("    path: '${_escape(path)}',")
      ..writeln("    contentType: '${contentTypeFor(path)}',")
      ..writeln("    etag: '$etag',")
      ..writeln('    rawLength: ${raw.length},')
      ..writeln('    gzipBase64:')
      ..writeln('${chunks.join('\n')},')
      ..writeln('  ),');
  }
  buf.writeln('};');
  return buf.toString();
}

String _escape(String s) =>
    s.replaceAll(r'\', r'\\').replaceAll("'", r"\'").replaceAll(r'$', r'\$');
